import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { resolve } from "node:path";

const root = fileURLToPath(new URL("../", import.meta.url));
const inventory = JSON.parse(await readFile(resolve(root, "spec/frontend-metadata/enum-constants.json"), "utf8"));
const categories = new Map();
for (const constant of inventory.constants) {
  for (const item of constant.codeValues ?? constant.members ?? []) {
    const value = item.value;
    const category = value.slice(value.lastIndexOf(":") + 1);
    if (!categories.has(category)) categories.set(category, new Set());
    categories.get(category).add(value);
  }
}
const codes = Object.fromEntries([...categories].sort(([a], [b]) => a.localeCompare(b, "en")).map(
  ([category, values]) => [category, [...values].sort()],
));
const output = `// Generated by scripts/generate-codes.mjs.\n` +
  `// Values observed in frontend constants; this is not a complete server enumeration.\n\n` +
  `export const observedCodes = ${JSON.stringify(codes, null, 2)} as const;\n\n` +
  `export type ObservedCodeCategory = keyof typeof observedCodes;\n` +
  `export type ObservedCode<K extends ObservedCodeCategory> = (typeof observedCodes)[K][number];\n`;
const destination = resolve(root, "packages/sdk/src/generated/codes.ts");
if (process.argv.includes("--check")) {
  if (await readFile(destination, "utf8").catch(() => "") !== output) throw new Error("Observed code constants are stale. Run pnpm generate.");
} else {
  await mkdir(resolve(root, "packages/sdk/src/generated"), { recursive: true });
  await writeFile(destination, output);
}
console.log(`Observed code categories: ${Object.keys(codes).length}.`);
