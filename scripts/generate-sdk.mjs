import { readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { resolve } from "node:path";

// This generator consumes interface facts, never executes downloaded application code.
const root = fileURLToPath(new URL("../", import.meta.url));
const spec = JSON.parse(await readFile(resolve(root, "spec/observed-endpoints.json"), "utf8"));
const supportedModes = new Map([
  ["envelope-body", "envelope"], ["json", "json"], ["json-or-text", "json-or-text"], ["blob", "bytes"],
]);
const streamModes = new Set(["ndjson", "byte-stream"]);
const catalogue = {};
const ids = new Set();
for (const operation of spec.operations) {
  if (ids.has(operation.operationId)) throw new Error(`Duplicate operation ID: ${operation.operationId}`);
  ids.add(operation.operationId);
  const mode = supportedModes.get(operation.responseMode);
  const path = operation.sdkPathTemplate;
  const handledLimitations = new Set(["Response handling requires an explicit decoder/mode"]);
  const formResponseHandled = operation.responseMode === "json-or-text" &&
    operation.sdkBasePathMatched === true && operation.executionLimitations.every((value) => handledLimitations.has(value));
  const safePath = typeof path === "string" && path.startsWith("/") && !path.startsWith("//");
  const requestExecutable = (operation.executable === true || formResponseHandled) && mode !== undefined && safePath;
  const streamExecutable = operation.streamExecutable === true && streamModes.has(operation.responseMode) && safePath;
  const transport = requestExecutable ? "request" : streamExecutable ? "stream" : "catalogue";
  const parameters = [...new Set(operation.parameters.map((parameter) => parameter.name))];
  const templates = `${path ?? ""}?${operation.queryTemplate ?? ""}`;
  const slots = [...templates.matchAll(/\{([pq]\d+)\}/g)].map((match) => match[1]);
  for (const name of slots) {
    if (!parameters.includes(name)) throw new Error(`Missing parameter ${name}: ${operation.operationId}`);
  }
  catalogue[operation.operationId] = {
    service: operation.sdkService,
    method: operation.method,
    path: path ?? operation.pathTemplate,
    query: operation.queryTemplate ?? "",
    responseMode: mode ?? "unsupported",
    streamResponseMode: streamModes.has(operation.responseMode) ? operation.responseMode : "unsupported",
    observedResponseMode: operation.responseMode,
    bodyEncoding: operation.body.encoding,
    effect: operation.effect,
    auth: operation.frontendAuth === "bearer-marker-false-or-default" ? "none"
      : operation.frontendAuth === "session-bearer-when-present" ? "optional" : "required",
    executable: requestExecutable || streamExecutable,
    transport,
    parameters,
  };
}

const counts = {
  observedOperations: spec.operations.length,
  executableOperations: Object.values(catalogue).filter((operation) => operation.executable).length,
  requestOperations: Object.values(catalogue).filter((operation) => operation.transport === "request").length,
  streamOperations: Object.values(catalogue).filter((operation) => operation.transport === "stream").length,
  unresolvedCallsites: spec.coverage.unresolvedCallsites,
};
const source = `// Generated by scripts/generate-sdk.mjs. Edit the discovery specification, then regenerate.\n` +
  `// Schemas and access rights of frontend-observed operations have not been live-validated.\n\n` +
  `export const catalogue = ${JSON.stringify(catalogue, null, 2)} as const;\n\n` +
  `export const coverage = ${JSON.stringify(counts, null, 2)} as const;\n`;
const destination = resolve(root, "packages/sdk/src/generated/catalogue.ts");
if (process.argv.includes("--check")) {
  const current = await readFile(destination, "utf8").catch(() => "");
  if (current !== source) throw new Error("Generated catalogue is stale. Run pnpm generate.");
  console.log(`Catalogue is current: ${counts.observedOperations} observed, ${counts.executableOperations} executable.`);
} else {
  await mkdir(resolve(root, "packages/sdk/src/generated"), { recursive: true });
  await writeFile(destination, source);
  console.log(`Generated ${counts.observedOperations} entries; ${counts.executableOperations} have an executable transport mapping.`);
}
